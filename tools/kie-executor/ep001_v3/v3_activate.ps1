# v3_activate.ps1 — запись пакетного разрешения пользователя в журнал, копии промптов в refs, стартовый баланс. Без расходов.
. (Join-Path $PSScriptRoot 'v3_lib.ps1')
if (@(Get-ChildItem -LiteralPath $Gen -Filter ($Pfx + '_journal_*.jsonl') -File).Count) { throw 'Журнал пакета уже существует — повторная активация не нужна.' }
if ((Get-Sha $PlanFile) -ne $PlanSha) { throw 'plan.json не совпал с зафиксированным коммитом.' }
if ((Get-Sha $Hero) -ne $HeroSha) { throw 'Исходник героя не совпал по SHA-256.' }
$plan = Get-Content -Raw -LiteralPath $PlanFile | ConvertFrom-Json -AsHashtable
$st = New-Stamp
$prompts = @()
foreach ($t in @($plan.image_tasks) + @($plan.video_tasks)) {
  $src = Join-Path $Dl ($t.prompt_file -replace '/', '__')
  $dst = Join-Path $Refs ($Pfx + '_' + [IO.Path]::GetFileName($t.prompt_file))
  if (Test-Path -LiteralPath $dst) { throw ('Промпт ' + $dst + ' уже есть.') }
  if ((Get-Sha $src) -ne $t.prompt_sha256) { throw ('Скачанный промпт ' + $src + ' не совпал с plan.json.') }
  [IO.File]::Copy($src, $dst)
  if ((Get-Sha $dst) -ne $t.prompt_sha256) { throw ('Копия ' + $dst + ' не совпала по SHA-256.') }
  $log = $dst -replace '\.txt$', '.log.txt'
  [IO.File]::WriteAllLines($log, [string[]]@(
      ([IO.Path]::GetFileName($dst) + ' | промпт ' + $t.id + ' EP001 V3 | ' + (Get-Item -LiteralPath $dst).Length + ' B | sha256=' + $t.prompt_sha256 + ' | сохранено ' + $st),
      ('источник: https://raw.githubusercontent.com/sINte3/CartoonReels/' + $Commit + '/episodes/EP001_V3/' + $t.prompt_file + ' (SHA-256 совпал с plan.json того же коммита)')
    ), $Utf8)
  $prompts += [ordered]@{ id = $t.id; file = $dst; sha256 = $t.prompt_sha256 }
}
Set-Key
try { $bal = Get-Balance } finally { $env:KIE_API_KEY = $null }
$jp = Join-Path $Gen ($Pfx + '_journal_' + $st + '.jsonl')
[IO.File]::WriteAllText($jp, '', $Utf8)
Add-Journal ([ordered]@{
    type         = 'activation'
    source       = 'Сообщение пользователя в чате Claude Code 08.11.2026: «Выполни EP001 V3 «Чисто. Почти.» целиком со звуком. Разрешаю расходы через Kie AI в пределах 600 кредитов… Это единое разрешение на весь пакет.»'
    cap          = $Cap
    allowed      = [ordered]@{ baseImages = 3; baseVideos = 2; extraImages = 2; extraVideos = 1; maxImageCreates = 5; maxVideoCreates = 3; topUp = $false; otherModelsOrProviders = $false; paidAudioServices = $false }
    instruction  = [ordered]@{ url = 'https://raw.githubusercontent.com/sINte3/CartoonReels/' + $Commit + '/episodes/EP001_V3/CLAUDE_PRODUCE_FULL_RU.md'; sha256 = '6c5c72ebd393400e43ec5ca054b741b554a5eeafe5c6a7d47c7869223909b77f' }
    commit       = $Commit
    planSha256   = $PlanSha
    hero         = [ordered]@{ file = $Hero; sha256 = $HeroSha; size = '941x1672' }
    prompts      = $prompts
    prices       = [ordered]@{
      checkedAt       = '2026-11-08 11:42 Asia/Tashkent'
      nanoBanana2_2K  = '12 кр ($0.06) за изображение — kie.ai/nano-banana-2; в таблице kie.ai/pricing у модели 3 варианта цены (1K/2K/4K), отдельной цены за число референсов нет'
      seedance2_720p  = '41 кр/с ($0.205/s) без видео-входа — kie.ai/seedance-2-0, вкладка «Seedance 2»; 4 с = 164 кр'
      audio           = 'generate_audio=true отдельно не тарифицируется: в kie.ai/pricing у bytedance/seedance-2 8 вариантов = 4 разрешения × с/без видео-входа; страница: «Audio is generated by default»; цены в бете'
      docsUnchangedSince = '2026-11-06 (nanobanana2.md 01c4f34f…, seedance-2.md d40c80d9…)'
    }
    expected     = [ordered]@{ base = 364; reserveMax = 188; maxTotal = 552 }
    balanceStart = $bal
  })
'Журнал: ' + $jp
'Стартовый баланс: ' + $bal + ' кр'
'Промпты в refs: ' + (($prompts | ForEach-Object { [IO.Path]::GetFileName($_.file) }) -join ', ')
